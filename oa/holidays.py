"""国家法定节假日 / 休息日判断（供考勤日历、每日工作汇总、未打卡提醒共用）"""

from datetime import date

# 各年份法定节假日放假日期区间（含调休后的连续放假日期）。
# 依据：国务院办公厅《关于2026年部分节假日安排的通知》（国办发明电〔2025〕7号）。
# 新年度公布后在此追加即可；未收录的年份仅星期日按休息日处理。
HOLIDAY_RANGES = {
    2026: [
        (date(2026, 1, 1), date(2026, 1, 3)),    # 元旦：1月1日-1月3日
        (date(2026, 2, 15), date(2026, 2, 23)),  # 春节：2月15日-2月23日
        (date(2026, 4, 4), date(2026, 4, 6)),    # 清明：4月4日-4月6日
        (date(2026, 5, 1), date(2026, 5, 5)),    # 劳动节：5月1日-5月5日
        (date(2026, 6, 19), date(2026, 6, 21)),  # 端午：6月19日-6月21日
        (date(2026, 9, 25), date(2026, 9, 27)),  # 中秋：9月25日-9月27日
        (date(2026, 10, 1), date(2026, 10, 7)),  # 国庆：10月1日-10月7日
    ],
}


def is_rest_day(d):
    """是否休息日：国家法定节假日放假日期 或 星期日"""
    for s, e in HOLIDAY_RANGES.get(d.year, []):
        if s <= d <= e:
            return True
    if d.weekday() == 6:  # 星期日
        return True
    return False
